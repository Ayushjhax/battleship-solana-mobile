/** The Flag Hall's denominator: "37 / 250". One number, from one place. */
export const COUNTRY_COUNT = COUNTRIES.length;

/**
 * The list's sort key, and the picker's.
 *
 * NOT a plain `<` comparison. 'Türkiye' > 'Tuvalu' in code-point order, so a
 * naive sort files it after Tuvalu — and a player scanning an alphabetical
 * list for Türkiye looks between Tunisia and Turkmenistan, gives up, and
 * concludes it is missing. Stripping the diacritic puts it where a reader
 * expects. The same applies to Côte d'Ivoire and São Tomé.
 *
 * `COUNTRIES` above is stored already sorted by this key, so the picker never
 * has to sort 199 rows at render time.
 */
export function sortKey(name: string): string {
  return name.normalize('NFD').replace(/\p{Mn}/gu, '').toUpperCase();
}

export function compareCountries(a: Country, b: Country): number {
  const ka = sortKey(a.name);
  const kb = sortKey(b.name);
  return ka < kb ? -1 : ka > kb ? 1 : 0;
}

const BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]));

export function countryByCode(code: string | null | undefined): Country | null {
  if (!code) return null;
  return BY_CODE.get(code.toUpperCase()) ?? null;
}

export function countryName(code: string | null | undefined): string {
  return countryByCode(code)?.name ?? 'Unknown';
}

export function isCountryCode(code: string): boolean {
  return BY_CODE.has(code.toUpperCase());
}

// ---------------------------------------------------------------------------
// The letter index (Appendix C)
// ---------------------------------------------------------------------------

export const ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'.split('');

/**
 * Which letters actually start a country, so the index can dim the rest.
 * A tappable letter that jumps nowhere is worse than one that is visibly off.
 */
export function activeLetters(): ReadonlySet<string> {
  return new Set(COUNTRIES.map((c) => sortKey(c.name).charAt(0)));
}

/**
 * The first row index for a letter, for the jump. Returns null for a letter
 * no country starts with, which the caller renders as dimmed and ignores.
 */
export function indexOfLetter(letter: string): number | null {
  const target = letter.toUpperCase();
  const at = COUNTRIES.findIndex((c) => sortKey(c.name).charAt(0) === target);
  return at === -1 ? null : at;
}

/** The list, grouped for a sectioned render. */
export function byLetter(): readonly { letter: string; countries: readonly Country[] }[] {
  const groups = new Map<string, Country[]>();
  for (const country of COUNTRIES) {
    const letter = sortKey(country.name).charAt(0);
    const bucket = groups.get(letter);
    if (bucket) bucket.push(country);
    else groups.set(letter, [country]);
  }
  return [...groups.entries()]
    .map(([letter, countries]) => ({ letter, countries }))
    .sort((a, b) => (a.letter < b.letter ? -1 : 1));
}
